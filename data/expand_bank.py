def main():
    qpath = ROOT / "questions.json"
    apath = ROOT / "answer_key.json"
    qdata = json.loads(qpath.read_text(encoding="utf-8"))
    adata = json.loads(apath.read_text(encoding="utf-8"))

    start_id = len(qdata["questions"]) + 1  # 應為 41
    added = []
    for k, (cat, qtext, opts, exp, src) in enumerate(N):
        if len(opts) != 4:
            raise SystemExit(f"第 {k} 題選項數不是 4: {qtext}")
        qid = start_id + k
        rotate = k % 4
        ordered = [opts[(j - rotate) % 4] for j in range(4)]  # 正解移到位置 rotate
        added.append({
            "id": qid, "category": cat, "question": qtext,
            "options": ordered,
        })
        adata["answers"].append({
            "id": qid, "answer": LETTERS[rotate],
            "answer_text": opts[0],
            "explanation": exp, "source": src,
        })

